export function getTranslations(locale: Locale): Dict {
  return translations[locale] || translations.ru
}

export const LocaleContext = createContext<{
  locale: Locale
  t: (key: string) => string
  setLocale: (l: Locale) => void
}>({
  locale: 'ru',
  t: (key: string) => translations.ru[key] || key,
  setLocale: () => {},
})

export function useLocale() {
  return useContext(LocaleContext)
}

export function detectLocale(): Locale {
  const path = window.location.pathname
  const match = path.match(/^\/(ru|en|de|fr|pt|zh)/)
  if (match) return match[1] as Locale

  for (const language of navigator.languages.length ? navigator.languages : [navigator.language]) {
    const locale = language.toLowerCase().split('-')[0]
    if (LOCALES.some(({ code }) => code === locale)) return locale as Locale
  }

  return 'en'
}
